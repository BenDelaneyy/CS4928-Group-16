###########################################
# BOUNDED RUN: hypothesis tests on the 12-project sample
# Re-runs the tests from crude-analysis.R / data-transformation.R and saves the console output as evidence.
# Run from the project root:  source("evidence/bounded_run/bounded_tests.R")
###########################################

library(lsr)

output_file <- "evidence/bounded_run/bounded_results_output.txt"
sink(output_file, split = TRUE)  # Writes to the file and still prints to the console

cat("Bounded run output -", format(Sys.time()), "\n")
cat("Data: Data/final_data_file_sample.csv (generated by Data/sample.py, seed 42)\n\n")

# Same preparation as crude-analysis.R
raw_df <- read.csv("Data/final_data_file_sample.csv")
raw_df <- subset(raw_df, select = -c(trimmed_languages))
raw_df$velocity_mean_end <- raw_df$velocity_mean_end + 0.01
raw_df$velocity_mean_start <- raw_df$velocity_mean_start + 0.01

cases_df <- raw_df[raw_df$MS.NonMS == 'MS',]
cases_endvelocity <- abs(cases_df$velocity_mean_end)
controls_df <- raw_df[raw_df$MS.NonMS == '~MS',]
controls_endvelocity <- abs(controls_df$velocity_mean_end)

cat("Cases (MS):\n"); print(cases_df$full_name)
cat("Controls (~MS):\n"); print(controls_df$full_name)
cat("\nMedian end velocity - cases:", median(cases_endvelocity), " controls:", median(controls_endvelocity), "\n")

# Normality (crude-analysis.R)
print(shapiro.test(cases_endvelocity))
print(shapiro.test(controls_endvelocity))

# Mann-Whitney (crude-analysis.R). Paper: two-sided p = 0.5987, one-sided p = 0.7013
print(wilcox.test(cases_endvelocity, controls_endvelocity, alternative = "two.sided", conf.int = T))
print(wilcox.test(cases_endvelocity, controls_endvelocity, alternative = "less", conf.int = T))

# Welch t-test on raw end velocity (crude-analysis.R)
print(t.test(cases_endvelocity, controls_endvelocity, var.equal = FALSE))

# Welch t-test and Cohen's d on cube-transformed end velocity (data-transformation.R / crude-analysis.R)
cases_endvelocity_cube <- cases_endvelocity^(1/3)
controls_endvelocity_cube <- controls_endvelocity^(1/3)
print(t.test(cases_endvelocity_cube, controls_endvelocity_cube, var.equal = FALSE))
cat("Cohen's d (pooled, cube-transformed):", cohensD(x = cases_endvelocity_cube, controls_endvelocity_cube, method = "pooled"), "\n")

sink()
cat("> Output saved to", output_file, "\n")
